#!/usr/bin/env bash
# UNVERIFIED DRAFT (2026-11-15): builds the AC6321A pin test as a JieLi SDK app
# (cpu/bd19, ac632n_hid) and packs app.bin. Never writes to a chip: the SDK's
# post-build script (isd_download -tonorflash) is turned off.
#
#   bash jl_build.sh            copy / patch the SDK work tree, build, pack
#
#   MK_JL_SDK   SDK clone, left untouched (default C:/Users/user/tools/sdk/fw-AC63_BT_SDK)
#   MK_JL_WORK  work tree made from it (default C:/Users/user/tools/jieli/pintest_sdk)
#   MK_JL_TOOLCHAIN  JL toolchain bin folder (default C:/JL/pi32/bin)
#
# Work tree = the parts of the SDK a bd19 build reads (apps/common, apps/hid,
# cpu/bd19, include_lib, tools). Config files are copied fresh from the SDK
# on every run, then patched (so the patch is always the same):
#   board_config.h      CONFIG_BOARD_AC6321A_STAND_KEYBOARD (USB user HID, keys off)
#   ..._keyboard_cfg.h  USB device (PC) on; debug UART0 off (its TX is USB0 DP);
#                       matrix keys and external MCU off; Bluetooth off
#   app_config.h        CONFIG_APP_STANDARD_KEYBOARD (builds usb_hid_devices.c);
#                       the SDK app file of that name is left out, ac6321a_hal.c
#                       registers the app instead
#   Makefile            pintest sources in, app_standard_keyboard.c out
# Output: $MK_JL_WORK/cpu/bd19/tools/sdk.elf and app.bin (copied to build/).
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
LOGIC=$HERE/../../ch32v203/test_ch32v203
SDK=${MK_JL_SDK:-C:/Users/user/tools/sdk/fw-AC63_BT_SDK}
WORK=${MK_JL_WORK:-C:/Users/user/tools/jieli/pintest_sdk}
TC=${MK_JL_TOOLCHAIN:-C:/JL/pi32/bin}
BOARD=apps/hid/board/bd19
CFG=$BOARD/board_ac6321a_stand_keyboard_cfg.h

[ -d "$SDK/cpu/bd19" ] || { echo "MK_JL_SDK: no cpu/bd19 in $SDK"; exit 1; }
[ -x "$TC/clang.exe" ] || [ -x "$TC/clang" ] || { echo "MK_JL_TOOLCHAIN: no clang in $TC"; exit 1; }

if [ ! -d "$WORK/cpu/bd19" ]; then
  echo "== copy SDK parts to $WORK"
  mkdir -p "$WORK/apps" "$WORK/cpu"
  cp -r "$SDK/apps/common" "$SDK/apps/hid" "$WORK/apps/"
  cp -r "$SDK/cpu/bd19" "$WORK/cpu/"
  cp -r "$SDK/include_lib" "$SDK/tools" "$WORK/"
  cp "$SDK/Makefile" "$SDK/LICENSE" "$WORK/"
fi

echo "== patch config"
for f in $BOARD/board_config.h $CFG apps/hid/include/app_config.h $BOARD/Makefile; do
  cp "$SDK/$f" "$WORK/$f"
done
# replace "#define NAME <old>" by "#define NAME <new>" and fail when absent
setdef() {
  local file=$WORK/$1 name=$2 val=$3
  grep -Eq "^[[:space:]]*#define[[:space:]]+$name[[:space:]]" "$file" || { echo "missing $name in $1"; exit 1; }
  sed -i -E "s|^([[:space:]]*#define[[:space:]]+$name)[[:space:]]+[^/]*|\1 $val |" "$file"
}
sed -i -E 's|^#define CONFIG_BOARD_AC632N_DEMO|// #define CONFIG_BOARD_AC632N_DEMO|; s|^// #define CONFIG_BOARD_AC6321A_STAND_KEYBOARD|#define CONFIG_BOARD_AC6321A_STAND_KEYBOARD|' "$WORK/$BOARD/board_config.h"
grep -q '^#define CONFIG_BOARD_AC6321A_STAND_KEYBOARD' "$WORK/$BOARD/board_config.h" || { echo "board_config.h patch failed"; exit 1; }
setdef $CFG TCFG_UART0_ENABLE DISABLE_THIS_MOUDLE
setdef $CFG TCFG_PC_ENABLE ENABLE_THIS_MOUDLE
setdef $CFG TCFG_MATRIX_KEY_ENABLE DISABLE_THIS_MOUDLE
setdef $CFG TCFG_EX_MCU_ENABLE DISABLE_THIS_MOUDLE
setdef $CFG TCFG_USER_BLE_ENABLE 0
# power: keep the SDK board defaults (DC-DC DCDC15 + LVD). The JUZH_3B4 board
# has the pin-2 SW inductor L1 (continuity confirmed 2026-11-15) and a good
# battery, so DCDC15 is correct and LVD can stay on. (The earlier LDO15/LVD0/
# LOWPOWER0 patch was based on a wrong "no inductor" reading and is reverted;
# the post-flash no-USB cause was not the power path. See docs note.)
setdef apps/hid/include/app_config.h CONFIG_APP_KEYBOARD 0
setdef apps/hid/include/app_config.h CONFIG_APP_STANDARD_KEYBOARD 1

echo "== sources"
mkdir -p "$WORK/apps/hid/pintest"
cp "$LOGIC/test_ch32v203.c" "$HERE/ac6321a_hal.c" "$HERE/ac6321a_hal.h" "$HERE/ac6321a_pins.h" "$WORK/apps/hid/pintest/"
cat > "$WORK/apps/hid/pintest/pintest_main.c" <<'EOF'
// generated by jl_build.sh: the shared pin test logic with the AC6321A layer
#define TEST_HAL_H "ac6321a_hal.h"
#define TEST_PINS_H "ac6321a_pins.h"
#include "test_ch32v203.c"
EOF
MK=$WORK/$BOARD/Makefile
grep -q 'examples/standard_keyboard/app_standard_keyboard.c' "$MK" || { echo "Makefile: app file line not found"; exit 1; }
sed -i 's|\.\./\.\./\.\./\.\./apps/hid/examples/standard_keyboard/app_standard_keyboard\.c|../../../../apps/hid/pintest/pintest_main.c \\\n\t../../../../apps/hid/pintest/ac6321a_hal.c|' "$MK"

echo "== build"
export PATH="$(cygpath -u "$TC"):$(cygpath -u "$WORK/tools/utils"):$PATH"
cd "$WORK/$BOARD"
mingw32-make -j8 RUN_POST_SCRIPT="cmd /c echo POST-SCRIPT-SKIPPED"

echo "== pack app.bin (the objcopy part of cpu/bd19/tools/download.bat)"
cd "$WORK/cpu/bd19/tools"
OC=$TC/llvm-objcopy.exe
for s in text data data_code overlay_aec overlay_aac overlay_aptx common; do
  "$OC" -O binary -j ".$s" sdk.elf "${s#overlay_}.bin"
done
banks=()
for i in $(seq 0 20); do
  "$OC" -O binary -j ".overlay_bank$i" sdk.elf "bank$i.bin"
  banks+=("bank$i.bin" 0x0)
done
./lz4_packet.exe -dict text.bin -input common.bin 0 "${banks[@]}" -o bank.bin
cat text.bin data.bin data_code.bin aec.bin aac.bin bank.bin aptx.bin > app.bin
rm -f bank*.bin common.bin text.bin data.bin aac.bin aec.bin aptx.bin data_code.bin
mkdir -p "$HERE/build"
cp sdk.elf app.bin "$HERE/build/"
ls -l "$HERE/build"
echo "OK: build/app.bin (application only; the flash image with uboot, config and"
echo "    partitions is made by isd_download, not run here)"
